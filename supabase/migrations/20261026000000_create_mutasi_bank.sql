-- 1. PEMBUATAN TABEL mutasi_bank SESUAI ERD
CREATE TABLE IF NOT EXISTS public.mutasi_bank (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  akun_bank_id bigint NOT NULL REFERENCES public.akun(id),
  tanggal date NOT NULL,
  deskripsi text NOT NULL,
  jumlah bigint NOT NULL CHECK (jumlah <> 0),
  saldo bigint,
  nama_file text NOT NULL,
  jurnal_id bigint REFERENCES public.jurnal(id),
  diimpor_oleh uuid NOT NULL REFERENCES public.profiles(id),
  diimpor_pada timestamptz DEFAULT now(),
  CONSTRAINT uq_mutasi_bank UNIQUE (akun_bank_id, tanggal, deskripsi, jumlah, saldo)
);

-- Penyesuaian constraint kolom untuk backward compatibility jika tabel sudah ada
DO $$
BEGIN
  -- Pastikan default now() pada diimpor_pada
  ALTER TABLE public.mutasi_bank ALTER COLUMN diimpor_pada SET DEFAULT now();
  
  -- Pastikan constraint UNIQUE ada jika sebelumnya belum terpasang
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'uq_mutasi_bank'
  ) THEN
    ALTER TABLE public.mutasi_bank 
      ADD CONSTRAINT uq_mutasi_bank UNIQUE (akun_bank_id, tanggal, deskripsi, jumlah, saldo);
  END IF;
END $$;

-- Indeks performa untuk query pencarian mutasi dan relasi jurnal
CREATE INDEX IF NOT EXISTS idx_mutasi_bank_akun_tanggal 
  ON public.mutasi_bank (akun_bank_id, tanggal DESC);

CREATE INDEX IF NOT EXISTS idx_mutasi_bank_jurnal_id 
  ON public.mutasi_bank (jurnal_id);

-- 2. ATURAN ROW LEVEL SECURITY (RLS)
ALTER TABLE public.mutasi_bank ENABLE ROW LEVEL SECURITY;

-- Bersihkan policy lama (jika ada) untuk menghindari konflik
DROP POLICY IF EXISTS "mutasi_bank_all_finance" ON public.mutasi_bank;
DROP POLICY IF EXISTS "mutasi_bank_select_finance" ON public.mutasi_bank;
DROP POLICY IF EXISTS "mutasi_bank_insert_akuntan" ON public.mutasi_bank;
DROP POLICY IF EXISTS "mutasi_bank_update_akuntan" ON public.mutasi_bank;

-- Policy 1: Direktur dan Akuntan bisa membaca (SELECT) semua data
CREATE POLICY "mutasi_bank_select_finance"
  ON public.mutasi_bank FOR SELECT
  TO authenticated
  USING (public.current_user_role() IN ('akuntan', 'direktur'));

-- Policy 2: Hanya Akuntan yang bisa memasukkan (INSERT) data
CREATE POLICY "mutasi_bank_insert_akuntan"
  ON public.mutasi_bank FOR INSERT
  TO authenticated
  WITH CHECK (public.current_user_role() = 'akuntan');

-- Policy 3: Hanya Akuntan yang bisa mengubah (UPDATE) data (misalnya saat mencocokkan jurnal_id)
CREATE POLICY "mutasi_bank_update_akuntan"
  ON public.mutasi_bank FOR UPDATE
  TO authenticated
  USING (public.current_user_role() = 'akuntan')
  WITH CHECK (public.current_user_role() = 'akuntan');
